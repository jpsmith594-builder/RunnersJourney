"""Shared geography for the portrait South Africa map.

Both tools/gen_map_art.py (draws the map tiles) and tools/gen_places.py (places
towns on it) import this, so a town's dot always lands where the artwork draws land.

The map is a plain latitude/longitude grid stretched to a 9:19 phone-shaped frame:
west coast on the left, east coast on the right, Cape Town at the bottom, the northern
provinces at the top. Everything is stretched vertically, so it is a stylised map,
not a true-shape one.
"""

# Frame: degrees covered by the artwork (left, right, top, bottom).
LNG0, LNG1 = 15.2, 34.2
LAT_N, LAT_S = -21.2, -35.2

# Full-frame pixel width of the base tile pyramid level 3. Height follows 9:19.
W3 = 3600
H3 = W3 * 19 // 9  # 7600


def proj(lat, lng):
    """Latitude/longitude -> position in the frame as fractions (0..1)."""
    return (lng - LNG0) / (LNG1 - LNG0), (LAT_N - lat) / (LAT_N - LAT_S)


def to_metric(fx, fy):
    """Frame fractions -> isotropic units (frame width = 9, height = 19)."""
    return fx * 9.0, fy * 19.0


