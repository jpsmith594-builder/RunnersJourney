// Builds assets/places/world.csv and lib/features/map/country_names.dart.
//
//   mkdir /tmp/gen && cd /tmp/gen && npm init -y
//   npm install all-the-cities country-state-city
//   NODE_PATH=/tmp/gen/node_modules node <repo>/tools/gen_world_places.js <repo>
//
// Data: GeoNames (geonames.org), CC BY 4.0, via the all-the-cities package.
// Keeps towns with 2000+ people, plus every South African town in the data.
const fs = require('fs');
const path = require('path');
const cities = require('all-the-cities');
const { Country } = require('country-state-city');

const repo = process.argv[2] || '.';
const rows = cities
  .filter((c) => c.population >= 2000 || c.country === 'ZA')
  .sort((a, b) => b.population - a.population)
  .map((c) =>
    [
      c.name.replace(/[|\n\r]/g, ' '),
      c.country,
      c.adminCode || '',
      c.loc.coordinates[1].toFixed(4),
      c.loc.coordinates[0].toFixed(4),
      c.population,
    ].join('|'),
  );
fs.writeFileSync(path.join(repo, 'assets/places/world.csv'), rows.join('\n') + '\n');

const names = Country.getAllCountries()
  .map((c) => `  '${c.isoCode}': '${c.name.replace(/'/g, "\\'")}',`)
  .join('\n');
fs.writeFileSync(
  path.join(repo, 'lib/features/map/country_names.dart'),
  `// GENERATED by tools/gen_world_places.js - edit that script, not this file.\n` +
    `/// Country names by two-letter code.\nconst Map<String, String> kCountryNames = {\n${names}\n};\n`,
);
console.log(rows.length, 'places');
